# -----------------------------------------------------------------------------
# 1. 摩擦係数・壁面せん断応力 (式24-28)
# -----------------------------------------------------------------------------

"""
    friction_factor_laminar(Re)

円管内層流の摩擦係数 (式27, Re<2300側)。
"""
friction_factor_laminar(Re) = 64 / Re

"""
    friction_factor_turbulent(Re)

円管内乱流の摩擦係数 (式27, Re≥2300側, Blasius式)。
"""
friction_factor_turbulent(Re) = 0.316 * Re^(-0.25)

"""
    wall_shear_stress(f, ρ, u)

摩擦係数fから壁面せん断応力τwを求める (式26)。
"""
wall_shear_stress(f, ρ, u) = (f / 8) * ρ * u^2

"""
    pressure_drop_single_phase(D, τw)

単相の単位長さあたりの圧力損失 [Pa/m] (式25, n=l または v)。
ΔPn = πDΔzτw/A_cross = 4τw/D。管の微小区間Δzでの力の釣り合い
(壁面せん断力 τw πDΔz = 圧力降下 ΔP A Δz) から導かれる。
式24のFw = sign(u)ΔPn は、式2の運動量式の摩擦項 [Pa/m = N/m³] に
そのまま対応する。
"""
pressure_drop_single_phase(D, τw) = 4 * τw / D

"""
    pressure_drop_twophase(ΔP_l, ΔP_v, C)

Lockhart-Martinelli型の二相圧力損失 (式28)。
Cは流動様式 (層流-層流、層流-乱流等の組み合わせ) に応じた係数で、
C_LM_table (下記) とheattransfer.jl側のブレンド関数で与える。
"""
pressure_drop_twophase(ΔP_l, ΔP_v, C) = ΔP_l + C * sqrt(ΔP_l * ΔP_v) + ΔP_v

"""
    C_LM_table

Lockhart-Martinelli型の二相圧力損失係数Cの参照表。
気相・液相それぞれのReynolds数が layer=2300 を境に層流/乱流の
どちらかで、4通りの組み合わせに対応する値を持つ (教科書の表その
ものであり、Level1として分岐を一切含まない定数データ)。

この2300という閾値は、式27の摩擦係数・式50のNuで既に使っている
層流⇔乱流の遷移基準と同じものなので、heattransfer.jl側で
ブレンドする際、同じ ε (ブレンド幅) を使い回せる。

実際の滑らかな補間 (気相・液相2つの独立なtanh重みによる
バイリニア型ブレンド) は heattransfer.jl (Level3) 側で行う。
"""
const C_LM_table = (
    gas_turb_liq_turb = 20.0,  # Re_gas>2300, Re_liq>2300
    gas_turb_liq_lam  = 12.0,  # Re_gas>2300, Re_liq<2300
    gas_lam_liq_turb  = 10.0,  # Re_gas<2300, Re_liq>2300
    gas_lam_liq_lam   = 5.0,   # Re_gas<2300, Re_liq<2300
)

# -----------------------------------------------------------------------------
# 2. 単相強制対流 (式49-50)
# -----------------------------------------------------------------------------

"""
    Nu_pipe_laminar()

円管内層流 (等温壁) のNusselt数 (式50, Re<2300側)。定数3.66。
"""
Nu_pipe_laminar() = 3.66

"""
    Nu_pipe_turbulent(Re, Pr, n)

円管内乱流のNusselt数 (式50, Re≥2300側, Dittus-Boelter式)。
n=0.4 (加熱時) または 0.3 (冷却時)。
"""
Nu_pipe_turbulent(Re, Pr, n) = 0.023 * Re^0.8 * Pr^n

"""
    h_from_Nu(Nu, k, D)

Nusselt数から熱伝達係数を求める (式49)。
"""
h_from_Nu(Nu, k, D) = Nu * k / D

# -----------------------------------------------------------------------------
# 3. 凝縮 (Shah, 2009) (式51-57)
# -----------------------------------------------------------------------------

"""
    Jv_shah(x, G, g, D, ρ_v, ρ_l)

Shahの式の無次元蒸気流束パラメータ Jv (式51)。
Regime I / II の判定に使う。
"""
Jv_shah(x, G, g, D, ρ_v, ρ_l) = x * G / sqrt(g * D * ρ_v * (ρ_l - ρ_v))

"""
    Z_shah(x, P_r)

Shahの式のZパラメータ (式52)。P_r は reduced pressure (P/Pcrit)。
Prandtl数のPrと紛らわしいため、reduced pressureは一貫してP_rと
表記する。
"""
Z_shah(x, P_r) = ((1 / x - 1)^0.8) * P_r^0.4

"""
    Jv_boundary_shah(Z)

Regime I/IIの境界値 (式52の判定基準: Jv ≥ 0.98(Z+0.263)^(-0.62) でRegime I)。
"""
Jv_boundary_shah(Z) = 0.98 * (Z + 0.263)^(-0.62)

"""
    h_LT_shah(k_l, D, Re_LT, Pr_l)

Shahの式の基準熱伝達係数 h_LT (式53)。
【確認済み (2026-11-02)】原典の式は h_LT = 0.023 Re_LT^0.8 Pr_L^0.4 k_L/D で、
k_l/D の因子を含む (原ドキュメントの表記に見えないだけ)。本実装は原典どおり。
"""
h_LT_shah(k_l, D, Re_LT, Pr_l) = 0.023 * (k_l / D) * Re_LT^0.8 * Pr_l^0.4

"""
    h_I_shah(h_LT, μ_l, μ_v, n, x, P_r)

Shahの式のRegime I 熱伝達係数 (式54)。P_r は reduced pressure。
"""
h_I_shah(h_LT, μ_l, μ_v, n, x, P_r) =
    h_LT * (μ_l / (14μ_v))^n * ((1 - x)^0.8 + (3.8 * x^0.76 * (1 - x)^0.04) / P_r^0.38)

"""
    n_shah(P_r)

式54で使う指数n (式55)。P_r は reduced pressure。
"""
n_shah(P_r) = 0.0058 + 0.557 * P_r

"""
    h_Nu_shah(Re_LS, ρ_l, ρ_v, g, k_l, μ_l)

Shahの式のRegime II 重力支配項 h_Nu (式56, Nusselt型膜状凝縮)。
"""
h_Nu_shah(Re_LS, ρ_l, ρ_v, g, k_l, μ_l) =
    1.32 * Re_LS^(-1 / 3) * (ρ_l * (ρ_l - ρ_v) * g * k_l^3 / μ_l^2)^(1 / 3)

# h_conv = h_I (Regime I) または h_I + h_Nu (Regime II) という式57の
# 切り替えは、Level3 (heattransfer.jl) でブレンドする。
# (原ドキュメントの式57は「h_I + h_LT」と書かれているが、原典は h_I + h_Nu。確認済み 2026-11-02)

# -----------------------------------------------------------------------------
# 4. 沸騰 (Chen) (式58-63)
# -----------------------------------------------------------------------------

"""
    h_mac_chen(k_l, D, Re_l, Pr_l, F)

Chenの式の巨視的対流項 (式59)。
"""
h_mac_chen(k_l, D, Re_l, Pr_l, F) = 0.023 * (k_l / D) * Re_l^0.8 * Pr_l^0.696 * F

"""
    h_mic_chen(k_l, cp_l, ρ_l, σ, μ_l, h_fg, ρ_v, ΔT_sup, ΔP_sat, S)

Chenの式の微視的核沸騰項 (式60, Forster-Zuber相関)。
ΔT_sup = T_wall - T_sat(P)、ΔP_sat = P_sat(T_wall) - P_l。
h_fg は原ドキュメントのλ (潜熱) に対応する。
"""
function h_mic_chen(k_l, cp_l, ρ_l, σ, μ_l, h_fg, ρ_v, ΔT_sup, ΔP_sat, S)
    coeff = k_l^0.79 * cp_l^0.45 * ρ_l^0.49 / (σ^0.5 * μ_l^0.29 * h_fg^0.24 * ρ_v^0.24)
    return 0.00122 * coeff * ΔT_sup^0.24 * ΔP_sat^0.75 * S
end

"""
    F_chen_highX(inv_Xtt)

Chenの式のF因子 (式61, 1/Xtt > 0.1 側)。

【修正済み】原ドキュメントは F=2.35(0.213+1/Xtt^0.736) という表記
(べき乗が1/Xttのみにかかる) だったが、これは1/Xtt=0.1の境界で
F=1.0に連続接続しない (検算により不連続と確認済み)。
Carey原典に基づき、べき乗が(1/Xtt+0.213)全体にかかる正しい形に
修正している。1/Xtt→0.1のときF→1.0に正しく収束する
(F_chen_lowX()の値と一致する)。
"""
F_chen_highX(inv_Xtt) = 2.35 * (inv_Xtt + 0.213)^0.736

"""
    F_chen_lowX()

Chenの式のF因子 (式61, 1/Xtt ≤ 0.1 側)。定数1.0。
"""
F_chen_lowX() = 1.0

"""
    S_chen(Re_tp)

Chenの式のサプレッション因子 (式62)。1本の式で層流〜乱流を
連続的にカバーしており、ブレンド不要。
"""
S_chen(Re_tp) = (1 + 2.56e-6 * Re_tp^1.17)^(-1)

"""
    Xtt_martinelli(x, ρ_v, ρ_l, μ_l, μ_v)

Martinelli parameter Xtt (式63)。
"""
Xtt_martinelli(x, ρ_v, ρ_l, μ_l, μ_v) = ((1 - x) / x)^0.9 * (ρ_v / ρ_l)^0.5 * (μ_l / μ_v)^0.1

# -----------------------------------------------------------------------------
# 5. Post-dryout沸騰 (Dougall-Rohsenow) (式64)
# -----------------------------------------------------------------------------

"""
    h_pd_dougall_rohsenow(k_v, D, Re_v, x, ρ_v, ρ_l, Pr_v)

ドライアウト後の熱伝達係数 (式64)。
"""
h_pd_dougall_rohsenow(k_v, D, Re_v, x, ρ_v, ρ_l, Pr_v) =
    0.023 * (k_v / D) * (Re_v * (x + (1 - x) * ρ_v / ρ_l))^0.8 * Pr_v^0.4

# -----------------------------------------------------------------------------
# 6. CC自然対流 (式65)
# -----------------------------------------------------------------------------

"""
    Nu_cc_conduction()

CC内部、伝導支配域のNusselt数 (式65, Ra<10^4側)。定数1.0。
"""
Nu_cc_conduction() = 1.0

"""
    Nu_cc_laminar(Ra)

CC内部、層流自然対流のNusselt数 (式65, 10^4<Ra<10^7側, 加熱上平板)。
"""
Nu_cc_laminar(Ra) = 0.54 * Ra^0.25

"""
    Nu_cc_turbulent(Ra)

CC内部、乱流自然対流のNusselt数 (式65, 10^7<Ra<10^11側, Daneyの式)。
水平円筒・密閉容器の実測値 (NBSIR 75-807) で裏付け済み。
"""
Nu_cc_turbulent(Ra) = 0.15 * Ra^(1 / 3)

# -----------------------------------------------------------------------------
# 7. 周囲環境への自然熱伝達 (Holman) (式66)
# -----------------------------------------------------------------------------

"""
    h_nc_holman(ΔT, D_out)

周囲環境への自然熱伝達係数 (式66)。
ΔT = T_wall - T_amb。ΔTが負になりうる場合は、呼び出し側で
soft_abs 等により非負にしてから渡すこと (本関数はΔT≥0を前提とする
教科書の式をそのまま実装したもの)。
"""
h_nc_holman(ΔT, D_out) = 1.32 * (ΔT / D_out)^0.25

# -----------------------------------------------------------------------------
# 8. グルーブ蒸気への過熱 (平板強制対流) (式67)
# -----------------------------------------------------------------------------

"""
    Nu_flatplate_laminar(Re, Pr)

平板強制対流、層流のNusselt数 (式67, Re<5×10^5側)。
"""
Nu_flatplate_laminar(Re, Pr) = 0.664 * Re^0.5 * Pr^(1 / 3)

"""
    Nu_flatplate_turbulent(Re, Pr)

平板強制対流、乱流のNusselt数 (式67, Re≥5×10^5側)。
"""
Nu_flatplate_turbulent(Re, Pr) = 0.0296 * Re^0.8 * Pr^(1 / 3)