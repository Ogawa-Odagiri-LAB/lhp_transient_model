# -----------------------------------------------------------------------------
# 1. tanhブレンド (状態依存の if 分岐の置き換え)
# -----------------------------------------------------------------------------

"""
    smooth_step(s, ε)

sの符号に応じて0→1へなめらかに遷移する重みを返す (tanhシグモイド)。
s ≫ ε で 1、s ≪ -ε で 0、s=0 で 0.5。blend_tanh の内部で使うほか、
2つ以上の重みを独立に作りたい場面 (例: 単相⇔二相の接続で、乾き度の
上端・下端それぞれにブレンド幅を設定する場合) で直接使うこともある。
"""
smooth_step(s, ε) = 0.5 * (1 + tanh(s / ε))

"""
    blend_tanh(a, b, s, ε)

sの符号に応じて a と b をなめらかに切り替える。
s ≫ ε で a に収束し、s ≪ -ε で b に収束する。

状態依存の if 分岐 (例: 「Re>2300なら乱流側の式、そうでなければ
層流側の式」) を置き換えるために使う。ε は遷移の幅で、物理的な
遷移域の広さ (例えばRe=2300±数百) に合わせて選ぶ。

使用例:
    Nu = blend_tanh(Nu_turb, Nu_lam, Re - 2300.0, ε_Re)
    (Re>2300 で Nu_turb に、Re<2300 で Nu_lam になめらかに近づく)
"""
function blend_tanh(a, b, s, ε)
    w = smooth_step(s, ε)
    return w * a + (1 - w) * b
end

# -----------------------------------------------------------------------------
# 2. soft-floor / safe_pow (分数べき乗のドメインエラー対策)
# -----------------------------------------------------------------------------

"""
    soft_floor(v, δ=1e-6)

vをδ以上になめらかに保つ (勾配を残したまま非負性・下限を保証する)。

分数べき乗 (x^0.76, (1-x)^0.04, Re^0.8 など) の底が、Newton反復の
中間反復で一時的に0や負の値を取り、ドメインエラー (複素数が返る、
またはNaN/Infになる) を起こすのを防ぐために使う。
δを十分小さく取れば、v ≫ δ の領域ではほぼ v に等しいので、通常の
運転条件での計算結果にはほとんど影響しない。

以前の議論で soft_clamp_positive と呼んでいたものと同じ関数。
"""
soft_floor(v, δ=1e-6) = δ + 0.5 * (v - δ + sqrt((v - δ)^2 + 4δ^2))

"""
    safe_pow(base, p; δ=1e-6)

base を soft_floor でδ以上に保ってから base^p を計算する。
Chenの式・Shahの式など、分数べき乗を含む相関式のあらゆる箇所に
機械的に適用できる、汎用の「安全なべき乗」。

使用例:
    h_mic_term = safe_pow(P_sat_Twall - P_l, 0.75)   # 式60の [Psat-Pl]^0.75
"""
safe_pow(base, p; δ=1e-6) = soft_floor(base, δ)^p

# -----------------------------------------------------------------------------
# 3. soft-abs (流れ方向反転への対応)
# -----------------------------------------------------------------------------

"""
    soft_abs(x, δ)

xの滑らかな絶対値 (√(x²+δ²))。x=0近傍でも微分可能。

質量流量・速度の符号が過渡的に反転しうる箇所 (例: Re の計算に使う
質量流量 m、CC自然対流のΔT=T_wall-T_fluid) で、abs(x) の代わりに
使う。δ ≪ 代表スケールであれば、|x| ≫ δ の領域ではほぼ |x| に等しい。
"""
soft_abs(x, δ) = sqrt(x^2 + δ^2)

# -----------------------------------------------------------------------------
# 4. soft-clamp (端点での特異性対策)
# -----------------------------------------------------------------------------

"""
    soft_clamp(x, lo, hi, ε=1e-3*(hi-lo))

xを[lo,hi]の範囲になめらかにクランプする。下側を滑らかなmax(x,lo)、
上側を滑らかなmin(·,hi) に順に通す構成 (soft_floor と同じ平方根型)。

端点 (例: CCの液体積分率が0または1に近づき、θ_liqの微分が発散する手前)
で、Newton反復に異常な値が渡らないようにする安全装置として使う。
εは丸める幅で、端から数ε以上離れた領域ではほぼ x そのものを返す
(誤差は ε²/(4|x-端|) 程度)。

【修正履歴】以前はシグモイドで実装していたが、あれはクランプではなく
全域をS字に押し潰す関数で、中間値 (x=0.3 → ≈0 など) が壊れていた。
現在の実装では中間域は恒等的に通る。
"""
function soft_clamp(x, lo, hi, ε=1e-3 * (hi - lo))
    y = 0.5 * (x + lo + sqrt((x - lo)^2 + ε^2))      # 下側: 滑らかな max(x, lo)
    return 0.5 * (y + hi - sqrt((y - hi)^2 + ε^2))   # 上側: 滑らかな min(y, hi)
end

# -----------------------------------------------------------------------------
# 5. べき乗ブレンド (Churchill-Usagi型、層流⇔乱流などの領域接続)
# -----------------------------------------------------------------------------

"""
    blend_power(a, b, n; floor=1e-12)

Churchill-Usagi型のべき乗ブレンド: (a^n + b^n)^(1/n)。
n→∞ で max(a,b) に収束する、滑らかな「max」の近似。

a,b はともに非負 (Nu, h など、2つの異なる極限での近似式の値) で
あることを前提とする。floor は、数値誤差で a や b がわずかに負に
なった場合の安全装置 (soft_floor を内部で適用する)。

層流則・乱流則のように、同じ物理量の異なる極限での近似式を1本に
統合する際に使う。どちらの項もゼロになる必要はなく、nの選び方に
応じて「どちらが相対的に優勢か」がなめらかに入れ替わるだけでよい
(以前の議論: 層流Nu・乱流Nuの交差点 Ra_c=(C_lam/C_turb)^12 など)。

使用例:
    Nu = blend_power(0.54*Ra^0.25, 0.15*Ra^(1/3), 6)
"""
function blend_power(a, b, n; floor=1e-12)
    return (soft_floor(a, floor)^n + soft_floor(b, floor)^n)^(1 / n)
end

# -----------------------------------------------------------------------------
# 6. soft-min / soft-max (log-sum-exp型、上限・下限クランプ用)
# -----------------------------------------------------------------------------

"""
    _logsumexp_stable(a, b, k)

(1/k)*log(exp(k*a) + exp(k*b)) を、オーバーフローなく計算する
内部ヘルパー (k*a, k*b が大きくなっても exp がInfにならないよう、
最大値を引いてから計算する標準的なlog-sum-expの数値安定化)。
soft_min / soft_max はこの関数を使って実装される。
"""
function _logsumexp_stable(a, b, k)
    m = max(k * a, k * b)
    return (m + log(exp(k * a - m) + exp(k * b - m))) / k
end

"""
    soft_max(a, b, k)

a,b の滑らかな最大値。k が大きいほどハードな max(a,b) に近づく。
"""
soft_max(a, b, k) = _logsumexp_stable(a, b, k)

"""
    soft_min(a, b, k)

a,b の滑らかな最小値。k が大きいほどハードな min(a,b) に近づく。

上限値によるクランプ (例: h_TP = min(h_TP, 10000.0) のような、
物理的な安全上限の適用) を、勾配を残したまま行いたい場合に使う。

使用例:
    h_TP_capped = soft_min(h_TP, 10000.0, 0.001)
"""
soft_min(a, b, k) = -_logsumexp_stable(-a, -b, k)